def _build_stage_flags(args: Namespace) -> list[str]:
    """Serialise the resolved build options back into CLI flags, so a
    subprocess stage builds exactly as ``build`` would here — explicit flags
    override whatever config the child process would otherwise re-load."""
    flags: list[str] = []
    if args.resources is not None:
        flags += ["--resources", str(args.resources)]
    if args.on_missing == "drop":
        flags.append("--drop-missing")
    if not args.compress:
        flags.append("--no-compress")
    if args.add_reroutes:
        flags.append("--add-reroutes")
    if args.spacing is not None:
        flags += ["--spacing", *(str(value) for value in args.spacing)]
    if args.iterations is not None:
        flags += ["--iterations", str(args.iterations)]
    if args.direction is not None:
        flags += ["--direction", args.direction]
    if args.socket_alignment is not None:
        flags += ["--socket-alignment", args.socket_alignment]
    if args.keep_reroutes_outside_frames:
        flags.append("--keep-reroutes-outside-frames")
    if not args.stack_collapsed:
        flags.append("--no-stack-collapsed")
    if args.stack_margin_y_fac is not None:
        flags += ["--stack-margin-y-fac", str(args.stack_margin_y_fac)]
    if args.optimize_sizes:
        flags.append("--optimize-sizes")
    return flags


def _dump_stage_flags(args: Namespace) -> list[str]:
    """Serialise the resolved dump options back into CLI flags, as
    :func:`_build_stage_flags` does for the build stage."""
    flags = ["--nodebpy-pkg", str(args.nodebpy_pkg)]
    if args.typed_api:
        flags.append("--typed-api")
    if args.snapshot_positions:
        flags.append("--snapshot-positions")
    if args.keep_reroutes:
        flags.append("--keep-reroutes")
    if not args.materials:
        flags.append("--no-materials")
    return flags


def run_stage(argv: list[str]) -> None:
    """Run one pipeline stage (any ``nodebpy.assets`` subcommand) in a fresh
    session — :func:`~nodebpy.assets.build_library` and
    :func:`~nodebpy.assets.dump_library` each require one, so ``check``
    cannot run its stages in this process.

    With the ``bpy`` module a plain interpreter carries a session; inside a
    full Blender (``bpy.app.binary_path`` non-empty) another Blender is
    spawned onto the CLI entry (``-b --factory-startup -P .../__main__.py --
    <argv>``), with an isolated extensions directory so the spawn can't pick
    up stale wheels.
    """
    import bpy  # deferred: only the spawn decision needs the session

    env = os.environ.copy()
    if bpy.app.binary_path:  # pragma: no cover - needs a full Blender
        env["BLENDER_USER_EXTENSIONS"] = tempfile.mkdtemp(prefix="nodebpy-ext-")
        entry = Path(__file__).with_name("__main__.py")
        cmd = [
            bpy.app.binary_path,
            "-b",
            "--factory-startup",
            "-P",
            str(entry),
            "--",
            *argv,
        ]
    else:
        cmd = [sys.executable, "-m", "nodebpy.assets", *argv]
    subprocess.run(cmd, check=True, env=env)


def compare_sources(source_dir: Path, redump_dir: Path) -> tuple[list[str], int]:
    """Compare a dumped source tree against a re-dump of its built library.

    Byte-exact, with two deliberate exemptions: ``_``-prefixed files at the
    source root (downstream runtime modules the dump never writes), and the
    top-level ``__init__.py`` when it is hand-written (the dump leaves it
    untouched in place, so the re-dump's generated marker is no divergence —
    :func:`_is_generated_init` semantics). Everything else must match
    exactly, file sets included: a file present on only one side is a
    failure. Returns the offending files (set differences first, then
    content differences, each sorted) and the number of ``.py`` modules
    compared.
    """

    def tree(root: Path) -> set[Path]:
        return {
            p.relative_to(root)
            for p in root.rglob("*")
            if p.is_file()
            and (p.suffix == ".py" or p.name == CATALOG_FILENAME)
            and "__pycache__" not in p.relative_to(root).parts
        }

    src_files = tree(source_dir)
    new_files = tree(redump_dir)
    src_files -= {
        f
        for f in src_files
        if len(f.parts) == 1 and f.name.startswith("_") and f.name != "__init__.py"
    }
    init = source_dir / "__init__.py"
    if init.is_file() and not _is_generated_init(init):
        src_files.discard(Path("__init__.py"))
        new_files.discard(Path("__init__.py"))

    problems = sorted(str(f) for f in src_files ^ new_files)
    matching = src_files & new_files
    problems += sorted(
        str(f)
        for f in matching
        if (source_dir / f).read_bytes() != (redump_dir / f).read_bytes()
    )
    modules = len({f for f in matching if f.suffix == ".py"})
    return problems, modules


def check_roundtrip(args: Namespace) -> None:
    """The ``check`` subcommand: verify the roundtrip fixed point — building
    the sources and dumping the result back out must reproduce them
    byte-for-byte. Catches hand-edited sources the dumper would normalise
    differently, stale-datablock shadowing from a resources ``.blend``, and
    nodebpy drift.

    The build and dump stages run via :func:`run_stage` into a temporary
    directory; the dump is anchored at the real source directory and
    ``.blend`` location (``--anchor``), so its typed-API ``PackageLibrary``
    paths come out byte-identical to the real sources despite being written
    somewhere else.
    """
    source_dir = Path(args.source)
    with tempfile.TemporaryDirectory(prefix="nodebpy-check-") as tmp:
        blend = Path(tmp) / "library.blend"
        redump = Path(tmp) / "sources"
        run_stage(["build", str(source_dir), str(blend), *_build_stage_flags(args)])
        run_stage(
            [
                "dump",
                str(blend),
                str(redump),
                "--anchor",
                str(source_dir),
                str(args.blend),
                *_dump_stage_flags(args),
            ]
        )
        problems, modules = compare_sources(source_dir, redump)
        if problems:
            print("Sources do not survive the build->dump roundtrip:")
            for name in problems:
                print(f"  {name}")
            print(
                "Rebuild and re-dump to normalise them:\n"
                "  python -m nodebpy.assets build && python -m nodebpy.assets dump"
            )
            raise SystemExit(1)
    print(f"Roundtrip OK: {modules} source modules reproduce exactly")
